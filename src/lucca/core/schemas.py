"""
Project Lucca — Core Pydantic Schemas & Data Contracts
"""

from enum import Enum
from typing import Optional, List, Dict, Any
from pydantic import BaseModel, Field

# ============================================================================
# Audio & Sensing Schemas
# ============================================================================

class AudioPacket(BaseModel):
    sample_rate: int = Field(default=16000, description="Sample rate in Hz")
    channels: int = Field(default=1, description="Mono channel")
    pcm_data: bytes = Field(..., description="Raw 16-bit signed PCM audio bytes")
    duration_ms: float = Field(..., description="Duration of packet in milliseconds")
    energy_level: float = Field(default=0.0, description="RMS energy")
    is_speech_final: bool = Field(default=True, description="VAD endpointing flag")

class VisemeFrame(BaseModel):
    timestamp_ms: float
    viseme_id: str = Field(..., description="Viseme classification: sil, aa, ee, ih, oh, ou, pp")
    intensity: float = Field(default=1.0, ge=0.0, le=1.0)

# ============================================================================
# Memory & Provenance Schemas
# ============================================================================

class MemoryProvenance(str, Enum):
    USER_EXPLICIT = "USER_EXPLICIT"         # Spoken by user during PTT turn
    TOOL_VERIFIED = "TOOL_VERIFIED"         # JSON payload verified from container tool
    LISP_ASSERTION = "LISP_ASSERTION"       # Deterministic rule derivation
    LLM_NARRATION = "LLM_NARRATION"         # FORBIDDEN for long-term memory write

class MemoryCommitPayload(BaseModel):
    entry_id: str = Field(..., description="Deterministic UUIDv5 or hash")
    content: str = Field(..., description="Normalized semantic text fact")
    provenance: MemoryProvenance
    signature_token: str = Field(..., description="HMAC-SHA256 signature generated by orchestrator")
    created_at_utc: float
    entities: List[str] = Field(default_factory=list, description="Extracted entity nodes")
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)

class WorkingMemoryState(BaseModel):
    task_id: str
    active_intent: str
    intermediate_tool_outputs: List[Dict[str, Any]] = Field(default_factory=list)
    step_count: int = 0
    max_steps: int = 8
    is_active: bool = True

# ============================================================================
# Router & Telemetry Schemas
# ============================================================================

class RouteAction(str, Enum):
    DIRECT_TO_LLM = "DIRECT_TO_LLM"
    CHECK_LISP_FIRST = "CHECK_LISP_FIRST"
    CALL_COMPILED_TOOL = "CALL_COMPILED_TOOL"
    SAFE_FALLBACK_ESCALATE = "SAFE_FALLBACK_ESCALATE"

class DecisionRecord(BaseModel):
    record_id: str
    timestamp_utc: float
    raw_query: str
    tabular_features: Dict[str, float] = Field(default_factory=dict)
    heuristic_recommendation: RouteAction
    model_prediction: Optional[RouteAction] = None
    calibrated_probabilities: Dict[str, float] = Field(default_factory=dict)
    conformal_prediction_set: List[RouteAction] = Field(default_factory=list)
    final_dispatched_action: RouteAction
    execution_duration_ms: float
    user_interrupted: bool = False
    task_success: Optional[bool] = None

# ============================================================================
# Sandbox Tool Schemas
# ============================================================================

class ToolExecutionRequest(BaseModel):
    call_id: str
    tool_name: str
    arguments: Dict[str, Any]
    timeout_seconds: float = Field(default=5.0, le=30.0)

class ToolExecutionResponse(BaseModel):
    call_id: str
    tool_name: str
    exit_code: int
    stdout: str
    stderr: str
    structured_data: Optional[Dict[str, Any]] = None
    execution_time_ms: float
    tamper_proof_token: str
